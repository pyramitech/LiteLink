using LiteLink.Shared;
using LiteLink.Transport;
using System.Collections.Concurrent;
using System.Net;
using System.Net.Quic;
using System.Net.Security;
using System.Security.Cryptography.X509Certificates;

namespace LiteLink.Quic
{
    public class LiteLinkQuicServerOptions
    {
        /// <summary>endpoint to listen on, port 0 picks a free port (read it back from LiteLinkQuicServer.LocalEndPoint)</summary>
        public IPEndPoint EndPoint { get; set; } = new IPEndPoint(IPAddress.Any, 0);

        /// <summary>
        /// server certificate — QUIC always runs over TLS 1.3. When not provided, a self-signed
        /// one is generated at StartAsync (clients must then disable certificate validation,
        /// e.g. QuicClientOptions.AllowInvalidCertificates)
        /// </summary>
        public X509Certificate2 Certificate { get; set; }

        /// <summary>ALPN protocol id, must match the client's; defaults to "litelink"</summary>
        public string ApplicationProtocol { get; set; } = "litelink";

        /// <summary>upper bound for a single message, protects against malformed/hostile length prefixes</summary>
        public int MaxFrameSize { get; set; } = 64 * 1024 * 1024;

        /// <summary>
        /// how many ordinary requests one connection may execute in parallel; the default of 1
        /// processes them sequentially in arrival order (like SignalR's
        /// MaximumParallelInvocationsPerClient), so a single client can't occupy unbounded server
        /// concurrency. Cheap system traffic (handshakes, invoke responses) bypasses the limit, and
        /// multichannel requests are governed per client by RpcLink.AllowMultiChannel instead.
        /// 0 or negative means unlimited.
        /// </summary>
        public int MaxParallelRequestsPerConnection { get; set; } = 1;

        /// <summary>
        /// custom dispatch target (e.g. an RpcGateway); when null, connections are routed into
        /// the process-wide RpcServer.Instance as usual
        /// </summary>
        public IRpcConnectionHandler Handler { get; set; }
    }

    /// <summary>
    /// Hosts the process-wide <see cref="RpcServer.Instance"/> over QUIC. Each client connection
    /// carries one bidirectional stream (opened by the client) that multiplexes requests, responses
    /// and server pushes with the same frame protocol as the TCP transport. Requires a platform with
    /// msquic and TLS 1.3 (check <see cref="IsSupported"/>), e.g. Windows 11+ or Linux with libmsquic.
    /// </summary>
    public class LiteLinkQuicServer : IAsyncDisposable
    {
        private readonly LiteLinkQuicServerOptions _options;
        private IRpcConnectionHandler _handler;
        private QuicListener _listener;
        private CancellationTokenSource _cts;
        private Task _acceptLoop;
        private readonly ConcurrentDictionary<QuicConnection, FramedDuplexChannel> _sessions
            = new ConcurrentDictionary<QuicConnection, FramedDuplexChannel>();

        /// <summary>errors that can't be surfaced to a caller; falls back to RpcServer.Instance.OnError when unset</summary>
        public Action<Exception> OnError { get; set; }

        /// <summary>the actual bound endpoint, useful when the options requested port 0</summary>
        public IPEndPoint LocalEndPoint => _listener?.LocalEndPoint;

        /// <summary>the certificate in use: the configured one, or the autogenerated self-signed one</summary>
        public X509Certificate2 Certificate { get; private set; }
        private bool _ownsCertificate;

        public static bool IsSupported => QuicListener.IsSupported;

        public LiteLinkQuicServer(LiteLinkQuicServerOptions options)
        {
            _options = options ?? throw new ArgumentNullException(nameof(options));
        }

        public async Task StartAsync()
        {
            if (_listener != null)
                throw new InvalidOperationException("The server is already started");
            if (!QuicListener.IsSupported)
                throw new PlatformNotSupportedException("QUIC is not supported on this platform (msquic or TLS 1.3 unavailable)");
            if (_options.Handler == null && RpcServer.Instance == null)
                throw new InvalidOperationException("RpcServer.Instance is not initialized, reference the generated [RpcServer] assembly first (or provide a custom Handler)");

            _handler = _options.Handler ?? new RpcServerConnectionHandler();

            Certificate = _options.Certificate;
            if (Certificate == null)
            {
                Certificate = SelfSignedCertificate.Create();
                _ownsCertificate = true;
            }

            var alpn = new SslApplicationProtocol(_options.ApplicationProtocol);
            _cts = new CancellationTokenSource();
            _listener = await QuicListener.ListenAsync(new QuicListenerOptions
            {
                ListenEndPoint = _options.EndPoint,
                ApplicationProtocols = new List<SslApplicationProtocol> { alpn },
                ConnectionOptionsCallback = (_, _, _) => ValueTask.FromResult(new QuicServerConnectionOptions
                {
                    DefaultStreamErrorCode = 0,
                    DefaultCloseErrorCode = 0,
                    ServerAuthenticationOptions = new SslServerAuthenticationOptions
                    {
                        ApplicationProtocols = new List<SslApplicationProtocol> { alpn },
                        ServerCertificate = Certificate
                    }
                })
            });

            _acceptLoop = AcceptLoopAsync(_cts.Token);
        }

        private async Task AcceptLoopAsync(CancellationToken cancellationToken)
        {
            while (!cancellationToken.IsCancellationRequested)
            {
                QuicConnection quicConnection;
                try
                {
                    quicConnection = await _listener.AcceptConnectionAsync(cancellationToken);
                }
                catch (Exception) when (cancellationToken.IsCancellationRequested)
                {
                    break;
                }
                catch (Exception ex)
                {
                    ReportError(ex);
                    continue;
                }

                _ = HandleConnectionAsync(quicConnection, cancellationToken);
            }
        }

        private async Task HandleConnectionAsync(QuicConnection quicConnection, CancellationToken cancellationToken)
        {
            QuicServerConnection connection = null;
            FramedDuplexChannel channel = null;
            var registered = false;
            try
            {
                if (_handler.IsShuttingDown)
                {
                    await quicConnection.DisposeAsync();
                    return;
                }

                connection = new QuicServerConnection();
                _handler.OnConnected(connection);
                registered = true;

                //the client opens the duplex stream; it becomes visible here with its first frame (the handshake)
                var stream = await quicConnection.AcceptInboundStreamAsync(cancellationToken);

                channel = new FramedDuplexChannel(stream, _options.MaxFrameSize)
                {
                    OnError = ReportError,
                    MaxParallelRequests = _options.MaxParallelRequestsPerConnection
                };
                channel.RequestHandler = data => _handler.Receive(connection, data);
                connection.AttachChannel(channel);
                _sessions.TryAdd(quicConnection, channel);

                await channel.RunAsync(cancellationToken);
            }
            catch (Exception ex)
            {
                if (!cancellationToken.IsCancellationRequested)
                    ReportError(ex);
            }
            finally
            {
                if (registered)
                    _handler.OnDisconnected(connection);
                connection?.MarkClosed();
                _sessions.TryRemove(quicConnection, out _);
                channel?.Dispose();
                try
                {
                    await quicConnection.DisposeAsync();
                }
                catch (Exception) { }
            }
        }

        public async Task StopAsync()
        {
            if (_listener == null)
                return;

            _cts.Cancel();

            foreach (var session in _sessions)
                session.Value.Dispose(); //unblocks the session read loops

            try
            {
                await _acceptLoop;
            }
            catch (Exception) { }

            await _listener.DisposeAsync();

            if (_ownsCertificate)
            {
                Certificate?.Dispose();
                _ownsCertificate = false;
            }
            Certificate = null;
            _listener = null;
        }

        public async ValueTask DisposeAsync()
        {
            await StopAsync();
        }

        private void ReportError(Exception ex)
        {
            (OnError ?? RpcServer.Instance?.OnError)?.Invoke(ex);
        }
    }

    /// <summary>server-side handle for one connected QUIC client; Invoke pushes a one-way message to it</summary>
    internal class QuicServerConnection : IConnection
    {
        //the channel only exists once the client's duplex stream arrives (with the handshake),
        //pushes issued before that wait for it instead of failing
        private readonly TaskCompletionSource<FramedDuplexChannel> _channelReady
            = new TaskCompletionSource<FramedDuplexChannel>(TaskCreationOptions.RunContinuationsAsynchronously);
        private volatile bool _closed;

        public bool IsConnected => !_closed;
        public bool IsConnecting => false;

        internal void AttachChannel(FramedDuplexChannel channel) => _channelReady.TrySetResult(channel);
        internal void MarkClosed()
        {
            _closed = true;
            _channelReady.TrySetException(new Exception("The connection closed before its stream was established"));
        }

        public Task Connect()
        {
            throw new NotSupportedException("This function is only supported on the client side");
        }

        public async Task<byte[]> Invoke(byte[] data)
        {
            var channel = await _channelReady.Task;
            await channel.SendPushAsync(data);
            return null; //server -> client responses are not supported, same as the SignalR transport
        }

        public Task Terminate()
        {
            if (_channelReady.Task.IsCompletedSuccessfully)
                _channelReady.Task.Result.Dispose(); //ends the session's read loop, which disconnects the client
            MarkClosed();
            return Task.CompletedTask;
        }
    }
}
