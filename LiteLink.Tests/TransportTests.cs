    internal static class TransportTestCertificate
    {
        /// <summary>self-signed localhost certificate usable for both TCP-TLS and QUIC tests</summary>
        public static X509Certificate2 Create()
        {
            using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
            var request = new CertificateRequest("CN=localhost", key, HashAlgorithmName.SHA256);
            //Schannel requires the serverAuth EKU for QUIC certificates
            request.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(
                new OidCollection { new Oid("1.3.6.1.5.5.7.3.1") }, false));
            var san = new SubjectAlternativeNameBuilder();
            san.AddDnsName("localhost");
            san.AddIpAddress(IPAddress.Loopback);
            request.CertificateExtensions.Add(san.Build());

            var cert = request.CreateSelfSigned(DateTimeOffset.UtcNow.AddDays(-1), DateTimeOffset.UtcNow.AddYears(1));
            //Schannel can't use ephemeral private keys, round-trip through PFX to persist the key
            return X509CertificateLoader.LoadPkcs12(cert.Export(X509ContentType.Pfx), null);
        }
    }

    /// <summary>
    /// End-to-end tests over real loopback TCP sockets: the same singleton server the in-memory
    /// tests use, but hosted by LiteLinkTcpServer and reached through the framed wire protocol.
    /// </summary>
    [Collection("RpcServer")]
    public class TcpTransportTests
    {
        private static async Task<(LiteLinkTcpServer Server, client::LiteLink.Client.RpcClient Client)> StartAsync(
            LiteLinkTcpServerOptions serverOptions = null, TcpConnectionOptions clientOptions = null)
        {
            var server = new LiteLinkTcpServer(serverOptions ?? new LiteLinkTcpServerOptions
            {
                Address = IPAddress.Loopback,
                Port = 0
            });
            server.Start();
            var rpc = TcpConnection.Create("127.0.0.1", server.Port, clientOptions);
            await rpc.Start();
            return (server, rpc);
        }

        [Fact]
        public async Task Tcp_ComplexModel_RoundTrips()
        {
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                var sent = new ComplexModel
                {
                    Id = 42,
                    Name = "over tcp ✓",
                    Numbers = new List<int> { 1, 2, 3 },
                    ChildMap = new Dictionary<int, ChildModel> { { 5, new ChildModel { Id = 5, Name = "five" } } },
                    Price = 19.95m,
                };

                var echoed = await rpc.Send<ComplexModel>("Test.EchoModel", sent);

                Assert.Equal(sent.Id, echoed.Id);
                Assert.Equal(sent.Name, echoed.Name);
                Assert.Equal(sent.Numbers, echoed.Numbers);
                Assert.Equal("five", echoed.ChildMap[5].Name);
                Assert.Equal(sent.Price, echoed.Price);
            }
        }

        [Fact]
        public async Task Tcp_Tls_WithProvidedCertificate_RoundTrips()
        {
            using var certificate = TransportTestCertificate.Create();
            var (server, rpc) = await StartAsync(
                new LiteLinkTcpServerOptions { Address = IPAddress.Loopback, Certificate = certificate },
                new TcpConnectionOptions { UseTls = true }); //invalid certs are accepted by default
            await using (server)
            {
                Assert.Equal("secure", await rpc.Send<string>("Test.BigEcho", "secure"));
                Assert.Same(certificate, server.Certificate);
            }
        }

        [Fact]
        public async Task Tcp_Tls_WithAutogeneratedCertificate_RoundTrips()
        {
            var (server, rpc) = await StartAsync(
                new LiteLinkTcpServerOptions { Address = IPAddress.Loopback, UseTls = true },
                new TcpConnectionOptions { UseTls = true }); //invalid certs are accepted by default
            await using (server)
            {
                Assert.NotNull(server.Certificate);
                Assert.Equal("secure", await rpc.Send<string>("Test.BigEcho", "secure"));
            }
        }

        [Fact]
        public async Task Tcp_BigPayload_CompressedInBothDirections()
        {
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                var payload = new string('x', 20000) + "END";
                Assert.Equal(payload, await rpc.Send<string>("Test.BigEcho", payload));
            }
        }

        [Fact]
        public async Task Tcp_Multichannel_CallsRunConcurrently()
        {
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                var timer = Stopwatch.StartNew();
                var results = await Task.WhenAll(Enumerable.Range(0, 20)
                    .Select(_ => rpc.SendMultiChannelMessage<int>("Test.Slow", null)));
                timer.Stop();

                Assert.All(results, r => Assert.Equal(42, r));
                Assert.True(timer.ElapsedMilliseconds < 1500, $"calls were serialized: {timer.ElapsedMilliseconds}ms");
            }
        }

        [Fact]
        public async Task Tcp_ServerPush_ReachesRegisteredClientFunction()
        {
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                var received = new TaskCompletionSource<PushModel>(TaskCreationOptions.RunContinuationsAsynchronously);
                rpc.RegisterFunction<PushModel>("TestPush", m => received.TrySetResult(m));

                await rpc.Send<object>("Test.Push", "hi over tcp");

                var pushed = await received.Task.WaitAsync(TimeSpan.FromSeconds(5));
                Assert.Equal("hi over tcp", pushed.Message);
            }
        }

        [Fact]
        public async Task Tcp_DefaultLimit_SerializesPlainRequests()
        {
            //MaxParallelRequestsPerConnection defaults to 1: concurrent plain sends from one
            //connection execute sequentially in arrival order
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                var timer = Stopwatch.StartNew();
                var results = await Task.WhenAll(Enumerable.Range(0, 3)
                    .Select(_ => rpc.Send<int>("Test.Slow", null))); //100ms each
                timer.Stop();

                Assert.All(results, r => Assert.Equal(42, r));
                Assert.True(timer.ElapsedMilliseconds >= 250, $"calls ran in parallel despite the default limit: {timer.ElapsedMilliseconds}ms");
            }
        }

        [Fact]
        public async Task Tcp_RaisedLimit_RunsPlainRequestsInParallel()
        {
            var (server, rpc) = await StartAsync(new LiteLinkTcpServerOptions
            {
                Address = IPAddress.Loopback,
                Port = 0,
                MaxParallelRequestsPerConnection = 20
            });
            await using (server)
            {
                var timer = Stopwatch.StartNew();
                var results = await Task.WhenAll(Enumerable.Range(0, 20)
                    .Select(_ => rpc.Send<int>("Test.Slow", null)));
                timer.Stop();

                Assert.All(results, r => Assert.Equal(42, r));
                Assert.True(timer.ElapsedMilliseconds < 1500, $"calls were serialized: {timer.ElapsedMilliseconds}ms");
            }
        }

        [Fact]
        public async Task Tcp_MultichannelWithGrant_RunsInParallelAtLimitOne()
        {
            //multichannel envelopes bypass the request gate: at the default limit of 1 they are
            //the (grantable) way for a client to run calls in parallel
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                rpc.MultiChannelByDefault = true;

                var timer = Stopwatch.StartNew();
                var results = await Task.WhenAll(Enumerable.Range(0, 20)
                    .Select(_ => rpc.Send<int>("Test.Slow", null)));
                timer.Stop();

                Assert.All(results, r => Assert.Equal(42, r));
                Assert.True(timer.ElapsedMilliseconds < 1500, $"calls were serialized: {timer.ElapsedMilliseconds}ms");
            }
        }

        [Fact]
        public async Task Tcp_ServerInvoke_CompletesAtLimitOne()
        {
            //AskClient awaits the client's reply mid-procedure; the reply arrives as a request
            //frame (invoke response, type 3) and must bypass the gate or this deadlocks at limit 1
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                rpc.ResponseTimeout = TimeSpan.FromSeconds(5); //fail fast instead of hanging if the bypass breaks
                rpc.RegisterFunction<string, string>("Client.Echo", s => "client:" + s);

                Assert.Equal("client:from-server", await rpc.Send<string>("Test.AskClient", null));
            }
        }

        [Fact]
        public async Task Tcp_Batching_WorksUnderDefaultLimit()
        {
            //batch envelopes (including compressed ones) run under the gate, this exercises that
            //classification end to end over a real socket
            var (server, rpc) = await StartAsync();
            await using (server)
            {
                rpc.BatchMode = client::LiteLink.Client.RpcBatchMode.Window;
                var payload = new string('b', 5000);

                var results = await Task.WhenAll(Enumerable.Range(0, 5)
                    .Select(i => rpc.Send<string>("Test.BigEcho", payload + i)));

                for (int i = 0; i < results.Length; i++)
                    Assert.Equal(payload + i, results[i]);
            }
        }

        [Fact]
        public async Task Tcp_ServerStop_FailsInFlightRequests()
        {
            var (server, rpc) = await StartAsync();
            var pending = rpc.Send<int>("Test.Slow", null);
            await server.StopAsync();

            await Assert.ThrowsAnyAsync<Exception>(() => pending);
        }

        [Fact]
        public async Task Tcp_ServerStop_FailsPendingMultichannelInstantly()
        {
            //a multichannel caller awaiting its response push has nothing in the transport's
            //pending-request table anymore; the disconnect callback must fail its channel slot
            //immediately instead of letting it wait out the full ResponseTimeout (60s default)
            var (server, rpc) = await StartAsync();
            var pending = rpc.SendMultiChannelMessage<int>("Test.Slow", null);
            await Task.Delay(30); //past the ack

            var timer = Stopwatch.StartNew();
            await server.StopAsync();
            await Assert.ThrowsAnyAsync<Exception>(() => pending);
            timer.Stop();

            Assert.True(timer.ElapsedMilliseconds < 5000, $"the multichannel call waited for its timeout: {timer.ElapsedMilliseconds}ms");
        }
    }

    /// <summary>
    /// End-to-end tests over real loopback QUIC connections (TLS 1.3 + ALPN). Skipped silently
    /// on platforms without msquic/TLS 1.3 support.
    /// </summary>
    [Collection("RpcServer")]
    public class QuicTransportTests
    {
        private static async Task<(LiteLinkQuicServer Server, client::LiteLink.Client.RpcClient Client)> StartAsync(
            X509Certificate2 certificate = null)
        {
            //no certificate = the server autogenerates a self-signed one at StartAsync
            var server = new LiteLinkQuicServer(new LiteLinkQuicServerOptions
            {
                EndPoint = new IPEndPoint(IPAddress.Loopback, 0),
                Certificate = certificate
            });
            await server.StartAsync();

            //no client options: invalid (self-signed) certs are accepted by default
            var rpc = QuicClientConnection.Create("127.0.0.1", server.LocalEndPoint.Port);
            await rpc.Start();
            return (server, rpc);
        }

        [Fact]
        public async Task Quic_ComplexModel_RoundTrips()
        {
            if (!LiteLinkQuicServer.IsSupported)
                return;

            //explicitly provided certificate, the other QUIC tests cover the autogenerated one
            using var certificate = TransportTestCertificate.Create();
            var (server, rpc) = await StartAsync(certificate);
            await using (server)
            {
                Assert.Same(certificate, server.Certificate);

                var sent = new ComplexModel
                {
                    Id = 7,
                    Name = "over quic ✓",
                    Numbers = new List<int> { 9, 8, 7 },
                    TupleList = new List<(int, ChildModel)> { (9, new ChildModel { Id = 9, Name = "nine" }) },
                };

                var echoed = await rpc.Send<ComplexModel>("Test.EchoModel", sent);

                Assert.Equal(sent.Id, echoed.Id);
                Assert.Equal(sent.Name, echoed.Name);
                Assert.Equal(sent.Numbers, echoed.Numbers);
                Assert.Equal("nine", echoed.TupleList[0].Item2.Name);
            }
        }

        [Fact]
        public async Task Quic_BigPayload_CompressedInBothDirections()
        {
            if (!LiteLinkQuicServer.IsSupported)
                return;

            var (server, rpc) = await StartAsync();
            await using (server)
            {
                Assert.NotNull(server.Certificate); //autogenerated
                var payload = new string('q', 20000) + "END";
                Assert.Equal(payload, await rpc.Send<string>("Test.BigEcho", payload));
            }
        }

        [Fact]
        public async Task Quic_Multichannel_CallsRunConcurrently()
        {
