using LiteLink.Client;
using LiteLink.Shared;
using LiteLink.Transport;
using System.Net;
using System.Net.Quic;
using System.Net.Security;
using System.Net.Sockets;

namespace LiteLink.Quic.Client
{
    public class QuicClientOptions
    {
        /// <summary>ALPN protocol id, must match the server's; defaults to "litelink"</summary>
        public string ApplicationProtocol { get; set; } = "litelink";

        /// <summary>server name used for TLS validation; defaults to the host passed to Create</summary>
        public string TlsTargetHost { get; set; }

        /// <summary>
        /// accept any server certificate (default true): the QUIC transport is meant for same-network
        /// setups where servers typically run autogenerated self-signed certificates. Set to false to
        /// enforce platform validation, or use <see cref="CertificateValidation"/> to pin a certificate.
        /// </summary>
        public bool AllowInvalidCertificates { get; set; } = true;

        /// <summary>custom certificate validation, overrides AllowInvalidCertificates when set</summary>
        public RemoteCertificateValidationCallback CertificateValidation { get; set; }

        /// <summary>upper bound for a single message, protects against malformed length prefixes</summary>
        public int MaxFrameSize { get; set; } = 64 * 1024 * 1024;
    }

    /// <summary>
    /// QUIC client transport (always TLS 1.3). Create an <see cref="RpcClient"/> with
    /// <see cref="Create(string, int, QuicClientOptions, Func{Task})"/>, then call RpcClient.Start()
    /// to connect and handshake, exactly like the SignalR and TCP transports. Requires a platform
    /// with msquic and TLS 1.3 (check <see cref="IsSupported"/>).
    /// </summary>
    public class QuicClientConnection : IConnection
    {
        private readonly string _host;
        private readonly int _port;
        private readonly QuicClientOptions _options;
        private readonly Func<Task> _reconnectAction;

        private QuicConnection _quicConnection;
        private FramedDuplexChannel _channel;
        private volatile bool _isConnected;
        private volatile bool _isConnecting;

        internal Action<byte[]> PushReceived;

        /// <summary>fires when the connection drops (or Terminate is called), so RpcClient can fail
        /// pending multichannel calls and queued batch items immediately instead of timing them out</summary>
        internal Action ConnectionClosed;

        /// <summary>errors that can't be surfaced to a caller (protocol violations, push handler crashes)</summary>
        public Action<Exception> OnError { get; set; }

        public bool IsConnected => _isConnected;
        public bool IsConnecting => _isConnecting;

        public static bool IsSupported => QuicConnection.IsSupported;

        private QuicClientConnection(string host, int port, QuicClientOptions options, Func<Task> reconnectAction)
        {
            _host = host;
            _port = port;
            _options = options ?? new QuicClientOptions();
            _reconnectAction = reconnectAction;
        }

        public static RpcClient Create(string host, int port, QuicClientOptions options = null, Func<Task> reconnectAction = null)
        {
            var connection = new QuicClientConnection(host, port, options, reconnectAction);
            var client = new RpcClient(connection);
            connection.PushReceived = client.Receive;
            connection.ConnectionClosed = client.OnConnectionLost;
            return client;
        }

        public async Task Connect()
        {
            _isConnecting = true;
            try
            {
                await CloseCurrentAsync();

                if (!IPAddress.TryParse(_host, out var address))
                {
                    var addresses = await Dns.GetHostAddressesAsync(_host);
                    address = addresses.FirstOrDefault(a => a.AddressFamily == AddressFamily.InterNetwork)
                        ?? addresses.First();
                }

                var quicConnection = await QuicConnection.ConnectAsync(new QuicClientConnectionOptions
                {
                    RemoteEndPoint = new IPEndPoint(address, _port),
                    DefaultStreamErrorCode = 0,
                    DefaultCloseErrorCode = 0,
                    ClientAuthenticationOptions = new SslClientAuthenticationOptions
                    {
                        ApplicationProtocols = new List<SslApplicationProtocol>
                        {
                            new SslApplicationProtocol(_options.ApplicationProtocol)
                        },
                        TargetHost = _options.TlsTargetHost ?? _host,
                        RemoteCertificateValidationCallback = GetValidationCallback()
                    }
                });

                //the single duplex stream that carries all frames; the server sees it once the
                //first frame (the handshake sent by RpcClient.Start) goes out
                var stream = await quicConnection.OpenOutboundStreamAsync(QuicStreamType.Bidirectional);

                var channel = new FramedDuplexChannel(stream, _options.MaxFrameSize)
                {
                    PushHandler = data => PushReceived?.Invoke(data),
                    OnError = ex => OnError?.Invoke(ex)
                };

                _quicConnection = quicConnection;
                _channel = channel;
                _isConnected = true;

                _ = RunAsync(channel, quicConnection);
            }
            finally
            {
                _isConnecting = false;
            }
        }

        private async Task RunAsync(FramedDuplexChannel channel, QuicConnection quicConnection)
        {
            await channel.RunAsync(CancellationToken.None);
            channel.Dispose();
            try
            {
                await quicConnection.DisposeAsync();
            }
            catch (Exception) { }

            //only tear down state if a newer Connect() hasn't already replaced this channel
            if (ReferenceEquals(_channel, channel))
            {
                _isConnected = false;
                ConnectionClosed?.Invoke(); //before any reconnect, so stale requests fail instantly
                if (_reconnectAction != null)
                {
                    try
                    {
                        await _reconnectAction();
                    }
                    catch (Exception ex)
                    {
                        OnError?.Invoke(ex);
                    }
                }
            }
        }

        public Task<byte[]> Invoke(byte[] data)
        {
            var channel = _channel;
            if (channel == null || !_isConnected)
                throw new InvalidOperationException("The connection is not established, call Connect() first");
            return channel.InvokeAsync(data);
        }

        public async Task Terminate()
        {
            _isConnected = false;
            await CloseCurrentAsync(); //nulls _channel, so RunAsync's teardown block won't also fire the callback
            ConnectionClosed?.Invoke();
        }

        private async Task CloseCurrentAsync()
        {
            var channel = _channel;
            _channel = null;
            channel?.Dispose();

            var quicConnection = _quicConnection;
            _quicConnection = null;
            if (quicConnection != null)
            {
                try
                {
                    await quicConnection.DisposeAsync();
                }
                catch (Exception) { }
            }
        }

        private RemoteCertificateValidationCallback GetValidationCallback()
        {
            if (_options.CertificateValidation != null)
                return _options.CertificateValidation;
            if (_options.AllowInvalidCertificates)
                return (sender, certificate, chain, errors) => true;
            return null; //default platform validation
        }
    }
}
