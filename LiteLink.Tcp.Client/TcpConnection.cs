using LiteLink.Client;
using LiteLink.Shared;
using LiteLink.Transport;
using System.Net.Security;
using System.Net.Sockets;

namespace LiteLink.Tcp.Client
{
    public class TcpConnectionOptions
    {
        /// <summary>wrap the connection in TLS; the server must be configured with a certificate</summary>
        public bool UseTls { get; set; }

        /// <summary>server name used for TLS validation; defaults to the host passed to Create</summary>
        public string TlsTargetHost { get; set; }

        /// <summary>
        /// accept any server certificate (default true): the TCP transport is meant for same-network
        /// setups where servers typically run autogenerated self-signed certificates. Set to false to
        /// enforce platform validation, or use <see cref="CertificateValidation"/> to pin a certificate.
        /// </summary>
        public bool AllowInvalidCertificates { get; set; } = true;

        /// <summary>custom certificate validation, overrides AllowInvalidCertificates when set</summary>
        public RemoteCertificateValidationCallback CertificateValidation { get; set; }

        /// <summary>upper bound for a single message, protects against malformed length prefixes</summary>
        public int MaxFrameSize { get; set; } = 64 * 1024 * 1024;
    }

    /// <summary>
    /// Raw TCP client transport. Create an <see cref="RpcClient"/> with
    /// <see cref="Create(string, int, TcpConnectionOptions, Func{Task})"/>, then call RpcClient.Start()
    /// to connect and handshake, exactly like the SignalR transport.
    /// </summary>
    public class TcpConnection : IConnection
    {
        private readonly string _host;
        private readonly int _port;
        private readonly TcpConnectionOptions _options;
        private readonly Func<Task> _reconnectAction;

        private TcpClient _tcpClient;
        private FramedDuplexChannel _channel;
        private volatile bool _isConnected;
        private volatile bool _isConnecting;

        internal Action<byte[]> PushReceived;

        /// <summary>fires when the connection drops (or Terminate is called), so RpcClient can fail
        /// pending multichannel calls and queued batch items immediately instead of timing them out</summary>
        internal Action ConnectionClosed;

        /// <summary>errors that can't be surfaced to a caller (protocol violations, push handler crashes)</summary>
        public Action<Exception> OnError { get; set; }

        public bool IsConnected => _isConnected;
        public bool IsConnecting => _isConnecting;

        private TcpConnection(string host, int port, TcpConnectionOptions options, Func<Task> reconnectAction)
        {
            _host = host;
            _port = port;
            _options = options ?? new TcpConnectionOptions();
            _reconnectAction = reconnectAction;
        }

        public static RpcClient Create(string host, int port, TcpConnectionOptions options = null, Func<Task> reconnectAction = null)
        {
            var connection = new TcpConnection(host, port, options, reconnectAction);
            var client = new RpcClient(connection);
            connection.PushReceived = client.Receive;
            connection.ConnectionClosed = client.OnConnectionLost;
            return client;
        }

        public async Task Connect()
        {
            _isConnecting = true;
            try
            {
                CloseCurrent();

                var tcp = new TcpClient { NoDelay = true };
                await tcp.ConnectAsync(_host, _port);

                Stream stream = tcp.GetStream();
                if (_options.UseTls)
                {
                    var ssl = new SslStream(stream, leaveInnerStreamOpen: false, GetValidationCallback());
                    await ssl.AuthenticateAsClientAsync(_options.TlsTargetHost ?? _host);
                    stream = ssl;
                }

                var channel = new FramedDuplexChannel(stream, _options.MaxFrameSize)
                {
                    PushHandler = data => PushReceived?.Invoke(data),
                    OnError = ex => OnError?.Invoke(ex)
                };

                _tcpClient = tcp;
                _channel = channel;
                _isConnected = true;

                _ = RunAsync(channel, tcp);
            }
            finally
            {
                _isConnecting = false;
            }
        }

        private async Task RunAsync(FramedDuplexChannel channel, TcpClient tcp)
        {
            await channel.RunAsync(CancellationToken.None);
            channel.Dispose();
            tcp.Dispose();

            //only tear down state if a newer Connect() hasn't already replaced this channel
            if (ReferenceEquals(_channel, channel))
            {
                _isConnected = false;
                ConnectionClosed?.Invoke(); //before any reconnect, so stale requests fail instantly
                if (_reconnectAction != null)
                {
                    try
                    {
                        await _reconnectAction();
                    }
                    catch (Exception ex)
                    {
                        OnError?.Invoke(ex);
                    }
                }
            }
        }

        public Task<byte[]> Invoke(byte[] data)
        {
            var channel = _channel;
            if (channel == null || !_isConnected)
                throw new InvalidOperationException("The connection is not established, call Connect() first");
            return channel.InvokeAsync(data);
        }

        public Task Terminate()
        {
            _isConnected = false;
            CloseCurrent(); //nulls _channel, so RunAsync's teardown block won't also fire the callback
            ConnectionClosed?.Invoke();
            return Task.CompletedTask;
        }

        private void CloseCurrent()
        {
            var channel = _channel;
            _channel = null;
            channel?.Dispose();
            _tcpClient?.Dispose();
            _tcpClient = null;
        }

        private RemoteCertificateValidationCallback GetValidationCallback()
        {
            if (_options.CertificateValidation != null)
                return _options.CertificateValidation;
            if (_options.AllowInvalidCertificates)
                return (sender, certificate, chain, errors) => true;
            return null; //default platform validation
        }
    }
}
