using LiteLink.Shared;
using LiteLink.Transport;
using System.Collections.Concurrent;
using System.Net;
using System.Net.Security;
using System.Net.Sockets;
using System.Security.Cryptography.X509Certificates;

namespace LiteLink.Tcp
{
    public class LiteLinkTcpServerOptions
    {
        public IPAddress Address { get; set; } = IPAddress.Any;

        /// <summary>port to listen on, 0 picks a free port (read it back from LiteLinkTcpServer.Port)</summary>
        public int Port { get; set; }

        /// <summary>
        /// wrap every connection in TLS; when no <see cref="Certificate"/> is provided, a
        /// self-signed one is generated at Start (clients must then disable certificate
        /// validation, e.g. TcpConnectionOptions.AllowInvalidCertificates)
        /// </summary>
        public bool UseTls { get; set; }

        /// <summary>optional server certificate; setting one implies TLS</summary>
        public X509Certificate2 Certificate { get; set; }

        /// <summary>upper bound for a single message, protects against malformed/hostile length prefixes</summary>
        public int MaxFrameSize { get; set; } = 64 * 1024 * 1024;

        /// <summary>
        /// how many ordinary requests one connection may execute in parallel; the default of 1
        /// processes them sequentially in arrival order (like SignalR's
        /// MaximumParallelInvocationsPerClient), so a single client can't occupy unbounded server
        /// concurrency. Cheap system traffic (handshakes, invoke responses) bypasses the limit, and
        /// multichannel requests are governed per client by RpcLink.AllowMultiChannel instead.
        /// 0 or negative means unlimited.
        /// </summary>
        public int MaxParallelRequestsPerConnection { get; set; } = 1;

        /// <summary>
        /// custom dispatch target (e.g. an RpcGateway); when null, connections are routed into
        /// the process-wide RpcServer.Instance as usual
        /// </summary>
        public IRpcConnectionHandler Handler { get; set; }
    }

    /// <summary>
    /// Hosts the process-wide <see cref="RpcServer.Instance"/> over raw TCP. Runs standalone
    /// (no ASP.NET required) and can serve alongside the SignalR and QUIC transports, all
    /// sharing the same RpcServer singleton and procedure table.
    /// </summary>
    public class LiteLinkTcpServer : IAsyncDisposable
    {
        private readonly LiteLinkTcpServerOptions _options;
        private IRpcConnectionHandler _handler;
        private TcpListener _listener;
        private CancellationTokenSource _cts;
        private Task _acceptLoop;
        private readonly ConcurrentDictionary<FramedDuplexChannel, TcpClient> _sessions
            = new ConcurrentDictionary<FramedDuplexChannel, TcpClient>();

        /// <summary>errors that can't be surfaced to a caller; falls back to RpcServer.Instance.OnError when unset</summary>
        public Action<Exception> OnError { get; set; }

        /// <summary>the actual bound port, useful when the options requested port 0</summary>
        public int Port { get; private set; }

        /// <summary>the certificate in use: the configured one, or the autogenerated self-signed one when UseTls is set without a certificate</summary>
        public X509Certificate2 Certificate { get; private set; }
        private bool _ownsCertificate;

        public LiteLinkTcpServer(LiteLinkTcpServerOptions options)
        {
            _options = options ?? new LiteLinkTcpServerOptions();
        }

        public void Start()
        {
            if (_listener != null)
                throw new InvalidOperationException("The server is already started");
            if (_options.Handler == null && RpcServer.Instance == null)
                throw new InvalidOperationException("RpcServer.Instance is not initialized, reference the generated [RpcServer] assembly first (or provide a custom Handler)");

            _handler = _options.Handler ?? new RpcServerConnectionHandler();

            Certificate = _options.Certificate;
            if (Certificate == null && _options.UseTls)
            {
                Certificate = SelfSignedCertificate.Create();
                _ownsCertificate = true;
            }

            _cts = new CancellationTokenSource();
            _listener = new TcpListener(_options.Address, _options.Port);
            _listener.Start();
            Port = ((IPEndPoint)_listener.LocalEndpoint).Port;
            _acceptLoop = AcceptLoopAsync(_cts.Token);
        }

        private async Task AcceptLoopAsync(CancellationToken cancellationToken)
        {
            while (!cancellationToken.IsCancellationRequested)
            {
                TcpClient tcp;
                try
                {
                    tcp = await _listener.AcceptTcpClientAsync(cancellationToken);
                }
                catch (Exception) when (cancellationToken.IsCancellationRequested)
                {
                    break;
                }
                catch (Exception ex)
                {
                    ReportError(ex);
                    continue;
                }

                _ = HandleClientAsync(tcp, cancellationToken);
            }
        }

        private async Task HandleClientAsync(TcpClient tcp, CancellationToken cancellationToken)
        {
            FramedDuplexChannel channel = null;
            TcpServerConnection connection = null;
            var registered = false;
            try
            {
                if (_handler.IsShuttingDown)
                {
                    tcp.Dispose();
                    return;
                }

                tcp.NoDelay = true;
                Stream stream = tcp.GetStream();

                if (Certificate != null)
                {
                    var ssl = new SslStream(stream, leaveInnerStreamOpen: false);
                    await ssl.AuthenticateAsServerAsync(Certificate);
                    stream = ssl;
                }

                channel = new FramedDuplexChannel(stream, _options.MaxFrameSize)
                {
                    OnError = ReportError,
                    MaxParallelRequests = _options.MaxParallelRequestsPerConnection
                };
                connection = new TcpServerConnection(channel);
                channel.RequestHandler = data => _handler.Receive(connection, data);

                _sessions.TryAdd(channel, tcp);
                _handler.OnConnected(connection);
                registered = true;

                await channel.RunAsync(cancellationToken);
            }
            catch (Exception ex)
            {
                if (!cancellationToken.IsCancellationRequested)
                    ReportError(ex);
            }
            finally
            {
                if (registered)
                    _handler.OnDisconnected(connection);
                connection?.MarkClosed();
                if (channel != null)
                {
                    _sessions.TryRemove(channel, out _);
                    channel.Dispose();
                }
                tcp.Dispose();
            }
        }

        public async Task StopAsync()
        {
            if (_listener == null)
                return;

            _cts.Cancel();
            _listener.Stop();

            foreach (var session in _sessions)
            {
                session.Key.Dispose(); //unblocks the session's read loop
                session.Value.Dispose();
            }

            try
            {
                await _acceptLoop;
            }
            catch (Exception) { }

            if (_ownsCertificate)
            {
                Certificate?.Dispose();
                _ownsCertificate = false;
            }
            Certificate = null;
            _listener = null;
        }

        public async ValueTask DisposeAsync()
        {
            await StopAsync();
        }

        private void ReportError(Exception ex)
        {
            (OnError ?? RpcServer.Instance?.OnError)?.Invoke(ex);
        }
    }

    /// <summary>server-side handle for one connected TCP client; Invoke pushes a one-way message to it</summary>
    internal class TcpServerConnection : IConnection
    {
        private readonly FramedDuplexChannel _channel;
        private volatile bool _closed;

        public TcpServerConnection(FramedDuplexChannel channel)
        {
            _channel = channel;
        }

        public bool IsConnected => !_closed;
        public bool IsConnecting => false;

        public Task Connect()
        {
            throw new NotSupportedException("This function is only supported on the client side");
        }

        public async Task<byte[]> Invoke(byte[] data)
        {
            await _channel.SendPushAsync(data);
            return null; //server -> client responses are not supported, same as the SignalR transport
        }

        public Task Terminate()
        {
            _channel.Dispose(); //ends the session's read loop, which disconnects the client
            return Task.CompletedTask;
        }

        internal void MarkClosed() => _closed = true;
    }
}
